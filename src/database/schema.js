/**
 * Schema - Database schema dumping and loading
 *
 * Provides functionality to dump the current database schema to a file
 * (db/schema.js) and load it back for fast schema reconstruction.
 *
 * This is used by:
 * - `brails db:migrate` - Auto-dumps schema after running migrations
 * - `brails db:schema:dump` - Manually dump current schema
 * - `brails db:schema:load` - Load schema without running migrations (fast CI setup)
 *
 * @module bun-on-rails/database/schema
 */

import { PostgresAdapter, TYPE_ALIASES } from './adapters/postgres.js'
import { pluralize } from '../support/inflector.js'
import path from 'path'
import fs from 'fs'

/**
 * Map PostgreSQL data types back to framework types
 */
const PG_TO_FRAMEWORK_TYPE = {
  'bigint': 'bigint',
  'integer': 'integer',
  'smallint': 'smallint',
  'boolean': 'boolean',
  'text': 'text',
  'character varying': 'string',
  'varchar': 'string',
  'timestamp without time zone': 'datetime',
  'timestamp with time zone': 'timestamptz',
  'date': 'date',
  'time without time zone': 'time',
  'time with time zone': 'time',
  'numeric': 'decimal',
  'decimal': 'decimal',
  'real': 'float',
  'double precision': 'double',
  'json': 'json',
  'jsonb': 'jsonb',
  'uuid': 'uuid',
  'bytea': 'binary',
  'inet': 'inet',
  'cidr': 'cidr',
  'macaddr': 'macaddr',
  'tsvector': 'tsvector',
  'point': 'point',
  'polygon': 'polygon',
  'ARRAY': 'array'
}

/**
 * Map ON DELETE/UPDATE action codes to names
 */
const FK_ACTION_MAP = {
  'a': 'NO ACTION',
  'r': 'RESTRICT',
  'c': 'CASCADE',
  'n': 'SET NULL',
  'd': 'SET DEFAULT'
}

/**
 * SchemaGenerator - Dumps database schema to db/schema.js
 *
 * Introspects the current database structure and generates a JavaScript
 * file that can recreate the schema without running migrations.
 *
 * @example
 * const generator = new SchemaGenerator(connection)
 * await generator.dump('./db/schema.js')
 */
/**
 * Order tables so each comes after every table its foreign keys reference, as
 * a schema dump must be: it creates tables with their foreign keys inline.
 * Independent tables come in alphabetical order, so dumps are stable. A self-reference, or a reference to a table outside `tables`, does
 * not hold a table back. A cycle between tables throws, naming them, rather
 * than writing a dump that cannot be loaded. Pinned by
 * test/database/schema_order.test.js.
 *
 * @param {string[]} tables
 * @param {Record<string, string[]>} dependsOn - table -> tables it references
 * @returns {string[]}
 */
export function orderTablesForCreate(tables, dependsOn) {
  const inDump = new Set(tables)
  const waitingOn = new Map(
    tables.map((t) => [t, new Set((dependsOn[t] || []).filter((d) => d !== t && inDump.has(d)))])
  )
  const byName = [...tables].sort()
  const ordered = []
  while (waitingOn.size > 0) {
    const ready = byName.find((t) => waitingOn.has(t) && waitingOn.get(t).size === 0)
    if (!ready) {
      throw new Error(
        `Cannot order the schema dump: foreign keys form a cycle between ${[...waitingOn.keys()].join(', ')}. ` +
          'A dump creates each table with its foreign keys inline, so a cycle cannot be loaded.'
      )
    }
    ordered.push(ready)
    waitingOn.delete(ready)
    for (const deps of waitingOn.values()) deps.delete(ready)
  }
  return ordered
}

export class SchemaGenerator {
  /**
   * Create a new SchemaGenerator
   * @param {Connection} db - Database connection
   * @param {Object} options - Generator options
   * @param {string} options.schema - PostgreSQL schema to introspect (default: 'public')
   */
  constructor(db, options = {}) {
    this.db = db
    this.schema = options.schema || 'public'
    this.adapter = new PostgresAdapter()
  }

  /**
   * Dump the current database schema to a file
   * @param {string} filePath - Path to write schema file
   * @returns {Promise<string>} Generated schema content
   */
  async dump(filePath) {
    const content = await this.generate()

    // Ensure directory exists
    const dir = path.dirname(filePath)
    await fs.promises.mkdir(dir, { recursive: true })

    // Write schema file
    await fs.promises.writeFile(filePath, content, 'utf8')

    return content
  }

  /**
   * Generate schema content without writing to file
   * @returns {Promise<string>} Generated schema JavaScript
   */
  async generate() {
    // Tables in creation order: every referenced table before its referrers
    const allTables = (await this.getTables()).filter(t => t !== 'schema_migrations')
    const dependsOn = {}
    for (const table of allTables) {
      dependsOn[table] = (await this.getForeignKeys(table)).map(fk => fk.foreign_table)
    }
    const tables = orderTablesForCreate(allTables, dependsOn)

    // Get schema version (latest migration)
    const version = await this.getSchemaVersion()

    // Build schema content
    const lines = [
      '/**',
      ' * Database Schema',
      ' *',
      ' * This file is auto-generated by BunOnRails after migrations.',
      ' * DO NOT EDIT MANUALLY - your changes will be overwritten.',
      ' *',
      ' * To recreate your database from this schema:',
      ' *   brails db:schema:load',
      ' *',
      ' * To update this file after changing migrations:',
      ' *   brails db:migrate',
      ' *   brails db:schema:dump',
      ' */',
      '',
      `export const schemaVersion = '${version}'`,
      '',
      '/**',
      ' * Apply this schema to a database',
      ' * @param {Object} db - Database connection with createTable method',
      ' */',
      'export async function up(db) {'
    ]

    // Generate table definitions
    for (const table of tables) {
      // Skip schema_migrations table
      if (table === 'schema_migrations') {
        continue
      }

      const tableLines = await this.generateTableDefinition(table)
      lines.push(...tableLines.map(l => '  ' + l))
      lines.push('')
    }

    // Close up function
    lines.push('}')
    lines.push('')

    // Generate down function (drop tables in reverse order)
    lines.push('/**')
    lines.push(' * Drop all tables')
    lines.push(' * @param {Object} db - Database connection')
    lines.push(' */')
    lines.push('export async function down(db) {')

    // Drop tables in reverse order (respecting foreign keys)
    const reversedTables = tables.filter(t => t !== 'schema_migrations').reverse()
    for (const table of reversedTables) {
      lines.push(`  await db.dropTable('${table}', { cascade: true })`)
    }

    lines.push('}')
    lines.push('')

    // Export table list
    lines.push('/**')
    lines.push(' * List of all tables in the schema')
    lines.push(' */')
    lines.push(`export const tables = ${JSON.stringify(tables.filter(t => t !== 'schema_migrations'), null, 2)}`)
    lines.push('')

    // Export default
    lines.push('export default { schemaVersion, up, down, tables }')
    lines.push('')

    return lines.join('\n')
  }

  /**
   * Get all tables in the database
   * @returns {Promise<string[]>}
   */
  async getTables() {
    const result = await this.db.query(`
      SELECT table_name
      FROM information_schema.tables
      WHERE table_schema = $1 AND table_type = 'BASE TABLE'
      ORDER BY table_name
    `, [this.schema])

    return result.map(row => row.table_name)
  }

  /**
   * Get the current schema version from migrations
   * @returns {Promise<string>}
   */
  async getSchemaVersion() {
    try {
      const result = await this.db.query(`
        SELECT version FROM schema_migrations
        ORDER BY version DESC
        LIMIT 1
      `)

      return result[0]?.version || '0'
    } catch (error) {
      // schema_migrations doesn't exist yet
      return '0'
    }
  }

  /**
   * Generate table definition code
   * @param {string} tableName - Table name
   * @returns {Promise<string[]>} Lines of code
   */
  async generateTableDefinition(tableName) {
    const columns = await this.getColumns(tableName)
    const indexes = await this.getIndexes(tableName)
    const foreignKeys = await this.getForeignKeys(tableName)

    const lines = [
      `await db.createTable('${tableName}', (t) => {`
    ]

    // Find primary key column
    const pkIndex = indexes.find(idx => idx.is_primary)
    const pkColumns = pkIndex?.columns || []

    // Generate column definitions
    for (const column of columns) {
      const colLine = this.generateColumnDefinition(column, pkColumns, foreignKeys)
      if (colLine) {
        lines.push(`  ${colLine}`)
      }
    }

    // Generate indexes (non-primary, non-foreign-key)
    for (const index of indexes) {
      if (index.is_primary) continue

      // Skip indexes on foreign key columns (they're created automatically)
      const fkColumns = foreignKeys.map(fk => fk.column_name)
      const isAutoFkIndex = index.columns.length === 1 &&
        fkColumns.includes(index.columns[0])
      if (isAutoFkIndex) continue

      const indexLine = this.generateIndexDefinition(index)
      if (indexLine) {
        lines.push(`  ${indexLine}`)
      }
    }

    lines.push('})')

    return lines
  }

  /**
   * Get column information for a table
   * @param {string} tableName - Table name
   * @returns {Promise<Object[]>}
   */
  async getColumns(tableName) {
    const result = await this.db.query(`
      SELECT
        c.column_name,
        c.data_type,
        c.udt_name,
        c.column_default,
        c.is_nullable,
        c.character_maximum_length,
        c.numeric_precision,
        c.numeric_scale,
        c.is_identity,
        c.identity_generation,
        (
          SELECT COUNT(*)
          FROM pg_constraint con
          JOIN pg_attribute a ON a.attnum = ANY(con.conkey) AND a.attrelid = con.conrelid
          WHERE con.contype = 'u'
            AND con.conrelid = (quote_ident($1) || '.' || quote_ident($2))::regclass
            AND a.attname = c.column_name
        ) > 0 AS is_unique
      FROM information_schema.columns c
      WHERE c.table_schema = $1 AND c.table_name = $2
      ORDER BY c.ordinal_position
    `, [this.schema, tableName])

    return result
  }

  /**
   * Get index information for a table
   * @param {string} tableName - Table name
   * @returns {Promise<Object[]>}
   */
  async getIndexes(tableName) {
    const result = await this.db.query(`
      SELECT
        i.relname AS index_name,
        am.amname AS index_type,
        idx.indisunique AS is_unique,
        idx.indisprimary AS is_primary,
        array_agg(a.attname ORDER BY array_position(idx.indkey, a.attnum)) AS columns,
        pg_get_expr(idx.indpred, idx.indrelid) AS where_clause
      FROM pg_index idx
      JOIN pg_class i ON i.oid = idx.indexrelid
      JOIN pg_class t ON t.oid = idx.indrelid
      JOIN pg_namespace n ON n.oid = t.relnamespace
      JOIN pg_am am ON am.oid = i.relam
      JOIN pg_attribute a ON a.attrelid = t.oid AND a.attnum = ANY(idx.indkey)
      WHERE n.nspname = $1 AND t.relname = $2
      GROUP BY i.relname, am.amname, idx.indisunique, idx.indisprimary, idx.indpred, idx.indrelid
      ORDER BY i.relname
    `, [this.schema, tableName])

    return result
  }

  /**
   * Get foreign key information for a table
   * @param {string} tableName - Table name
   * @returns {Promise<Object[]>}
   */
  async getForeignKeys(tableName) {
    const result = await this.db.query(`
      SELECT
        conname AS constraint_name,
        a.attname AS column_name,
        cl.relname AS foreign_table,
        af.attname AS foreign_column,
        confdeltype AS on_delete,
        confupdtype AS on_update
      FROM pg_constraint c
      JOIN pg_namespace n ON n.oid = c.connamespace
      JOIN pg_class t ON t.oid = c.conrelid
      JOIN pg_class cl ON cl.oid = c.confrelid
      JOIN pg_attribute a ON a.attrelid = t.oid AND a.attnum = ANY(c.conkey)
      JOIN pg_attribute af ON af.attrelid = cl.oid AND af.attnum = ANY(c.confkey)
      WHERE n.nspname = $1 AND t.relname = $2 AND c.contype = 'f'
      ORDER BY conname
    `, [this.schema, tableName])

    return result
  }

  /**
   * Generate column definition code
   * @param {Object} column - Column info
   * @param {string[]} pkColumns - Primary key column names
   * @param {Object[]} foreignKeys - Foreign key definitions
   * @returns {string|null} Column definition line or null to skip
   */
  generateColumnDefinition(column, pkColumns, foreignKeys) {
    const {
      column_name,
      data_type,
      udt_name,
      column_default,
      is_nullable,
      character_maximum_length,
      numeric_precision,
      numeric_scale,
      is_identity,
      is_unique
    } = column

    // Skip if this is the id column (primary key bigserial)
    if (pkColumns.includes(column_name) &&
        (data_type === 'bigint' || udt_name === 'int8') &&
        (column_default?.includes('nextval') || is_identity === 'YES')) {
      return "t.id()"
    }

    // Skip UUID primary key handled separately
    if (pkColumns.includes(column_name) && data_type === 'uuid') {
      return "t.id({ uuid: true })"
    }

    // Check if this is a foreign key reference
    const fk = foreignKeys.find(f => f.column_name === column_name)
    if (fk) {
      return this.generateReferenceDefinition(column, fk)
    }

    // Handle timestamps
    if (column_name === 'created_at' || column_name === 'updated_at') {
      // These are typically added together via timestamps()
      if (column_name === 'created_at') {
        return 't.timestamps()'
      }
      return null // Skip updated_at, it's included in timestamps()
    }

    // Map PostgreSQL type to framework type
    const frameworkType = this.mapDataType(data_type, udt_name)

    // Build column definition
    let line = `t.${frameworkType}('${column_name}'`

    // Add type options
    const typeOptions = []
    if (frameworkType === 'string' && character_maximum_length && character_maximum_length !== 255) {
      typeOptions.push(`limit: ${character_maximum_length}`)
    }
    if ((frameworkType === 'decimal' || frameworkType === 'numeric') && numeric_precision) {
      typeOptions.push(`precision: ${numeric_precision}`)
      if (numeric_scale) {
        typeOptions.push(`scale: ${numeric_scale}`)
      }
    }

    if (typeOptions.length > 0) {
      line += `, { ${typeOptions.join(', ')} }`
    }

    line += ')'

    // Add modifiers
    if (is_nullable === 'NO') {
      line += '.notNull()'
    }

    if (is_unique) {
      line += '.unique()'
    }

    // Handle default values
    if (column_default !== null && !column_default.includes('nextval')) {
      const defaultVal = this.formatDefaultValue(column_default, data_type)
      if (defaultVal !== null) {
        line += `.default(${defaultVal})`
      }
    }

    return line
  }

  /**
   * Generate reference (foreign key) definition code
   * @param {Object} column - Column info
   * @param {Object} fk - Foreign key info
   * @returns {string}
   */
  generateReferenceDefinition(column, fk) {
    const {
      column_name,
      is_nullable
    } = column

    const {
      foreign_table,
      foreign_column,
      on_delete,
      on_update
    } = fk

    // Infer the reference name from column name
    // e.g., user_id -> user, author_id -> author
    const refName = column_name.replace(/_id$/, '')

    // Build options
    const options = []

    // Spell out the table only when references() would not infer it: the
    // same pluralize() rule, so a dump loads back to the same foreign key.
    if (foreign_table !== pluralize(refName)) {
      options.push(`table: '${foreign_table}'`)
    }

    // If column name doesn't follow convention
    if (column_name !== `${refName}_id`) {
      options.push(`column: '${column_name}'`)
    }

    // If foreign column is not 'id'
    if (foreign_column !== 'id') {
      options.push(`foreignKey: '${foreign_column}'`)
    }

    // ON DELETE action
    const onDeleteAction = FK_ACTION_MAP[on_delete] || 'NO ACTION'
    if (onDeleteAction !== 'NO ACTION') {
      options.push(`onDelete: '${onDeleteAction}'`)
    }

    // ON UPDATE action
    const onUpdateAction = FK_ACTION_MAP[on_update] || 'NO ACTION'
    if (onUpdateAction !== 'NO ACTION') {
      options.push(`onUpdate: '${onUpdateAction}'`)
    }

    let line = `t.references('${refName}'`

    if (options.length > 0) {
      line += `, { ${options.join(', ')} }`
    }

    line += ')'

    // Add notNull if not nullable
    if (is_nullable === 'NO') {
      line += '.notNull()'
    }

    return line
  }

  /**
   * Generate index definition code
   * @param {Object} index - Index info
   * @returns {string}
   */
  generateIndexDefinition(index) {
    const {
      columns,
      is_unique,
      index_type,
      where_clause
    } = index

    const colsArg = columns.length === 1
      ? `'${columns[0]}'`
      : `[${columns.map(c => `'${c}'`).join(', ')}]`

    const options = []

    if (is_unique) {
      options.push('unique: true')
    }

    if (index_type && index_type !== 'btree') {
      options.push(`using: '${index_type}'`)
    }

    if (where_clause) {
      options.push(`where: '${where_clause.replace(/'/g, "\\'")}'`)
    }

    let line = `t.index(${colsArg}`

    if (options.length > 0) {
      line += `, { ${options.join(', ')} }`
    }

    line += ')'

    return line
  }

  /**
   * Map PostgreSQL data type to framework type
   * @param {string} dataType - PostgreSQL data type
   * @param {string} udtName - User-defined type name
   * @returns {string}
   */
  mapDataType(dataType, udtName) {
    // Check direct mapping
    if (PG_TO_FRAMEWORK_TYPE[dataType]) {
      return PG_TO_FRAMEWORK_TYPE[dataType]
    }

    // Check TYPE_ALIASES
    if (TYPE_ALIASES[dataType]) {
      return TYPE_ALIASES[dataType]
    }

    // Handle arrays
    if (dataType === 'ARRAY') {
      // udtName contains the base type prefixed with _ (e.g., _int4 -> int4)
      // We return 'array' as the framework type
      return 'array'
    }

    // Handle varchar with length extracted
    if (dataType.startsWith('character varying') || dataType.startsWith('varchar')) {
      return 'string'
    }

    // Handle numeric with precision
    if (dataType.startsWith('numeric') || dataType.startsWith('decimal')) {
      return 'decimal'
    }

    // Default to the raw type
    console.warn(`[Schema] Unknown data type: ${dataType} (${udtName}), using 'text'`)
    return 'text'
  }

  /**
   * Format a default value for code generation
   * @param {string} defaultValue - PostgreSQL default expression
   * @param {string} dataType - Column data type
   * @returns {string|null}
   */
  formatDefaultValue(defaultValue, dataType) {
    if (defaultValue === null || defaultValue === undefined) {
      return null
    }

    // Handle common SQL functions
    const upperDefault = defaultValue.toUpperCase()

    if (upperDefault === 'NOW()' ||
        upperDefault === 'CURRENT_TIMESTAMP' ||
        upperDefault.includes('NOW()') ||
        upperDefault.includes('CURRENT_TIMESTAMP')) {
      return "'NOW()'"
    }

    if (upperDefault === 'CURRENT_DATE') {
      return "'CURRENT_DATE'"
    }

    if (upperDefault.includes('GEN_RANDOM_UUID') ||
        upperDefault.includes('UUID_GENERATE')) {
      return "'gen_random_uuid()'"
    }

    // Handle boolean
    if (dataType === 'boolean') {
      if (defaultValue === 'true' || defaultValue === 't') {
        return 'true'
      }
      if (defaultValue === 'false' || defaultValue === 'f') {
        return 'false'
      }
    }

    // Handle numeric types
    if (['integer', 'bigint', 'smallint', 'numeric', 'decimal', 'real', 'double precision'].includes(dataType)) {
      // Extract numeric value from cast if present
      const numMatch = defaultValue.match(/^'?(-?\d+(?:\.\d+)?)'?(?:::.*)?$/)
      if (numMatch) {
        return numMatch[1]
      }
    }

    // Handle string with type cast (e.g., 'value'::character varying)
    const stringMatch = defaultValue.match(/^'([^']*)'(?:::.*)?$/)
    if (stringMatch) {
      return `'${stringMatch[1].replace(/'/g, "\\'")}'`
    }

    // Handle JSON/JSONB
    if (dataType === 'json' || dataType === 'jsonb') {
      const jsonMatch = defaultValue.match(/^'([^']*)'::jsonb?$/)
      if (jsonMatch) {
        return `'${jsonMatch[1]}'`
      }
    }

    // Handle arrays
    if (dataType === 'ARRAY') {
      if (defaultValue === "'{}'::text[]" || defaultValue.match(/^'\{\}'::.*\[\]$/)) {
        return '[]'
      }
    }

    // For complex expressions, wrap in raw
    return `{ raw: '${defaultValue.replace(/'/g, "\\'")}' }`
  }
}

/**
 * SchemaLoader - Loads db/schema.js and applies to database
 *
 * Used for fast database setup in CI/CD environments without
 * running individual migrations.
 *
 * @example
 * const loader = new SchemaLoader(connection)
 * await loader.load('./db/schema.js')
 */
/**
 * Versions of the migration files in `dir` at or before `version`.
 *
 * @param {string} dir
 * @param {string} version
 * @returns {string[]}
 */
function migrationVersionsUpTo(dir, version) {
  if (!fs.existsSync(dir)) return []
  return fs
    .readdirSync(dir)
    .map((file) => file.match(/^(\d+)_.*\.js$/)?.[1])
    .filter((v) => v && BigInt(v) <= BigInt(version))
    .sort()
}

export class SchemaLoader {
  /**
   * Create a new SchemaLoader
   * @param {Connection} db - Database connection
   */
  constructor(db) {
    this.db = db
  }

  /**
   * Load and apply schema from file
   * @param {string} filePath - Path to schema.js
   * @returns {Promise<void>}
   */
  async load(filePath) {
    // Import the schema module
    const schemaModule = await import(filePath)

    if (typeof schemaModule.up !== 'function') {
      throw new Error(`Schema file ${filePath} does not export an 'up' function`)
    }

    // Create a migration-like context
    const { Migration } = await import('./migration.js')
    const migration = new Migration(this.db)

    // Run the schema
    await schemaModule.up(migration)

    // Mark the schema version, and every migration file up to it, as run, so a
    // later migrate does not re-run what the schema already contains.
    if (schemaModule.schemaVersion && schemaModule.schemaVersion !== '0') {
      await this.recordVersion(schemaModule.schemaVersion)
      const migrationsDir = path.join(path.dirname(filePath), 'migrations')
      for (const version of migrationVersionsUpTo(migrationsDir, schemaModule.schemaVersion)) {
        await this.recordVersion(version)
      }
    }
  }

  /**
   * Record schema version in schema_migrations
   * @param {string} version - Schema version
   * @returns {Promise<void>}
   */
  async recordVersion(version) {
    // Ensure schema_migrations table exists
    await this.db.query(`
      CREATE TABLE IF NOT EXISTS "schema_migrations" (
        "version" VARCHAR(255) PRIMARY KEY,
        "executed_at" TIMESTAMP DEFAULT NOW()
      )
    `)

    // Check if version already recorded
    const existing = await this.db.query(
      'SELECT version FROM schema_migrations WHERE version = $1',
      [version]
    )

    if (existing.length === 0) {
      await this.db.query(
        'INSERT INTO schema_migrations (version) VALUES ($1)',
        [version]
      )
    }
  }

  /**
   * Drop all tables and reload schema
   * @param {string} filePath - Path to schema.js
   * @returns {Promise<void>}
   */
  async reset(filePath) {
    // Import the schema to get table list
    const schemaModule = await import(filePath)

    // Drop all tables in reverse order
    if (typeof schemaModule.down === 'function') {
      const { Migration } = await import('./migration.js')
      const migration = new Migration(this.db)
      await schemaModule.down(migration)
    }

    // Also drop schema_migrations
    await this.db.query('DROP TABLE IF EXISTS schema_migrations CASCADE')

    // Load fresh schema
    await this.load(filePath)
  }
}

/**
 * Dump schema to db/schema.js after migrations
 *
 * This is the main entry point called by MigrationRunner after migrations.
 *
 * @param {Connection} db - Database connection
 * @param {string} appRoot - Application root directory
 * @returns {Promise<string>} Path to generated schema file
 */
export async function dumpSchema(db, appRoot) {
  const generator = new SchemaGenerator(db)
  const schemaPath = path.join(appRoot, 'db', 'schema.js')

  await generator.dump(schemaPath)
  console.log(`Schema dumped to ${schemaPath}`)

  return schemaPath
}

/**
 * Load schema from db/schema.js
 *
 * This is the main entry point for schema:load.
 *
 * @param {Connection} db - Database connection
 * @param {string} appRoot - Application root directory
 * @returns {Promise<void>}
 */
export async function loadSchema(db, appRoot) {
  const loader = new SchemaLoader(db)
  const schemaPath = path.join(appRoot, 'db', 'schema.js')

  // Check if schema file exists
  try {
    await fs.promises.access(schemaPath)
  } catch (error) {
    throw new Error(`Schema file not found: ${schemaPath}. Run 'brails db:migrate' first.`)
  }

  await loader.load(schemaPath)
  console.log(`Schema loaded from ${schemaPath}`)
}

export default {
  SchemaGenerator,
  SchemaLoader,
  dumpSchema,
  loadSchema
}
